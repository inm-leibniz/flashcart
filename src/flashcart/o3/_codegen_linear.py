"""Generate Triton kernels for equivariant linear maps and their derivatives.

The generated module contains one layout slot per supported tensor rank.
The rowwise kernel computes ``(A_l @ op(W_l) + B_l @ op(V_l)) * scale_l``,
with either term enabled as needed. The weight-gradient kernel computes
``scale_l * grad_out_l.T @ B_l``. These two operations also supply the
products needed when differentiating the backward calculation.

Each program selects a tensor-rank slot. Compile-time guards remove
inactive ranks. Rowwise outputs use independent stores. Weight gradients
also use independent stores unless the row reduction is divided between
programs, in which case contributions are added atomically. Autotuning
resets outputs that accumulate contributions between trial launches.

Configuration filters limit float64 accumulator tiles and estimate shared
memory required by pipelined matrix-product inputs. If no shared-memory
configuration fits, the smallest estimate is retained so Triton can report
the allocation failure. Filtering avoids failed tuning trials retaining
GPU tensors in exception tracebacks.

The Python module ``flashcart.o3._linear`` loads the generated source from the
cache, supplies layout metadata, and registers the operations with PyTorch.
"""

from typing import List

_MODULE_DOCSTRING = '"""Auto-generated by flashcart.o3._codegen_linear.build_triton_linear_module_source."""'

